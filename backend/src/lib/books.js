let supabase;
if (process.env.SUPABASE_URL && process.env.SUPABASE_ANON_KEY) {
  supabase = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_ANON_KEY, { auth: { persistSession: false } });
  console.log('[DB] Supabase client initialized');
} else {
  console.log('[DB] No Supabase credentials — using in-memory demo catalogue');
}

export async function listBooks({ q = '', category = '', sort = 'featured', page = 1, limit = 50 } = {}) {
  let books = demoBooks.filter(b => b.is_active !== false);

  if (supabase) {
    const { data, error } = await supabase.from('books')
      .select('id,title,author,category,price,old_price,rating,review_count,cover_url,description,stock,featured,isbn')
      .eq('is_active', true);
    if (error) throw new Error('Could not load books from database');
    books = data ?? [];
  }

  const query = q.trim().toLowerCase();
  books = books.filter(b =>
    (!query || `${b.title} ${b.author} ${b.category} ${b.description || ''} ${b.isbn || ''}`.toLowerCase().includes(query)) &&
    (!category || category === 'All books' || b.category.toLowerCase() === category.toLowerCase()),
  );

  if (sort === 'price-asc') books.sort((a, b) => a.price - b.price);
  else if (sort === 'price-desc') books.sort((a, b) => b.price - a.price);
  else if (sort === 'rating') books.sort((a, b) => b.rating - a.rating);
  else if (sort === 'newest') books.sort((a, b) => (b.id > a.id ? -1 : 1));
  else if (sort === 'popular') books.sort((a, b) => b.review_count - a.review_count);
  else books.sort((a, b) => Number(Boolean(b.featured)) - Number(Boolean(a.featured)));

  return books;
}

export function getCategories() { return categories; }
