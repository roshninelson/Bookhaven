/**
 * Retrieve preview pages for a given book ID, applying the preview limit.
 */
export function getBookPreview(bookId) {
  const preview = bookPreviews[String(bookId)];
  if (!preview) {
    return {
      has_preview: false,
      message: 'Preview coming soon for this title.',
      pages: [],
      total_pages: 0,
      preview_limit: 0,
    };
  }

  const limit = Math.min(preview.preview_limit || 6, preview.pages.length);
  const slicedPages = preview.pages.slice(0, limit);

  return {
    has_preview: true,
    preview_limit: limit,
    total_pages: slicedPages.length,
    pages: slicedPages,
  };
}
